def translate_text(text, lang="en"):
    """
    Translate an English UI string to Swahili if lang is 'sw'.
    Returns original text if lang is 'en' or translation not found.
    """
    if not text or lang != "sw":
        return text
    clean_text = text.strip()
    return TRANSLATIONS_SW.get(clean_text, text)

